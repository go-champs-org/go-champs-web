/**
 * Path allowlist for edge routing: CMS path -> apps/public path.
 *
 * Only paths that already exist as real pages in apps/public belong here
 * (verified 2026-08-28 against apps/public/app/[locale]/**). Anything absent
 * falls through to the CMS SPA, so a missing entry degrades to today's
 * behavior rather than a 404.
 *
 * Kept free of Workers types so the CMS test runner can exercise it directly;
 * the Worker entry point (apps/cms/worker/index.ts) is the only consumer.
 * See docs/superpowers/specs/2026-07-30-apps-public-institucional-design.md §3.3.
 */

/**
 * Paths apps/public serves under its own name, forwarded verbatim instead of
 * rewritten. Without these the pages render but every local asset — the navbar
 * logo included — resolves against the CMS and comes back as its index.html.
 * Remote images are unaffected: they are absolute URLs to other hosts.
 *
 * None of these collide with the CMS, whose own public/ holds only flat files
 * (favicon.ico, manifest.json, ios-icon.png, logo-with-name-black.png) plus
 * CRA's /static/.
 */
const PASSTHROUGH_PREFIXES = [
  '/_next/', // Next's build output
  '/logo/', // apps/public/public/*
  '/photos/',
  '/illustrations/',
  '/fonts/',
  '/api/' // route handlers backing the client islands
];

/** Metadata routes generated by app/robots.ts and app/sitemap.ts. */
const PASSTHROUGH_EXACT = ['/robots.txt', '/sitemap.xml'];

/**
 * apps/public's own locale-prefixed URL space (next-intl). Its NavBar, locale
 * switcher and hreflang tags all link to /pt/... and /en/..., so those have to
 * reach apps/public — otherwise they fall through to the CMS, whose router
 * matches nothing and renders a blank page.
 *
 * Matched as a whole segment: the CMS routes /:organizationSlug at this same
 * position, so /ptbr must stay with the CMS. No organization uses "pt" or "en"
 * as its slug (checked against the staging API, 2026-08-28).
 */
const PASSTHROUGH_LOCALES = ['pt', 'en'];

export const isPublicPassthroughPath = (pathname: string): boolean =>
  PASSTHROUGH_PREFIXES.some(prefix => pathname.startsWith(prefix)) ||
  PASSTHROUGH_EXACT.includes(pathname) ||
  PASSTHROUGH_LOCALES.some(
    locale => pathname === `/${locale}` || pathname.startsWith(`/${locale}/`)
  );

/** A rule returns null when the path matched its shape but is not its to give. */
type Rewrite = [RegExp, (match: RegExpMatchArray) => string | null];

const SLUG = '([^/]+)';

/**
 * First path segments that can never be an organization slug, because the CMS
 * routes them itself. Taken from the static routes App.tsx declares ahead of
 * /:organizationSlug/:tournamentSlug — react-router matches in order, and the
 * tournament-root rule below has no literal segment to tell it apart, so it
 * would otherwise swallow /Organization/acme and /Invite/:id.
 */
const CMS_RESERVED_SEGMENTS = [
  'About',
  'Account',
  'AccountRecovery',
  'AccountReset',
  'Contact',
  'Faq',
  'Invite',
  'Organization',
  'Search',
  'SignIn',
  'SignUp',
  'TermsBR',
  'UseAsApp'
];

/**
 * App.tsx declares these with a trailing `*` (/PrivacyPolicy*,
 * /FacebookSignUp*), which matches any segment that starts with them.
 */
const CMS_RESERVED_SEGMENT_PREFIXES = ['PrivacyPolicy', 'FacebookSignUp'];

const isReservedByCms = (segment: string): boolean =>
  CMS_RESERVED_SEGMENTS.includes(segment) ||
  CMS_RESERVED_SEGMENT_PREFIXES.some(prefix => segment.startsWith(prefix));

const ROUTES: Rewrite[] = [
  [/^\/$/, () => '/pt'],

  // lote 2 — institucional. Case sensitive, mirroring the CMS's
  // `<Route sensitive>` definitions in src/App.tsx.
  [/^\/About$/, () => '/pt/about'],
  [/^\/Faq$/, () => '/pt/faq'],
  [/^\/Contact$/, () => '/pt/contact'],
  [/^\/PrivacyPolicyBR$/, () => '/pt/privacy'],
  [/^\/TermsBR$/, () => '/pt/terms'],

  // lote 1 — rotas de leitura por torneio
  [
    new RegExp(`^/${SLUG}/${SLUG}/GameView/${SLUG}$`),
    m => `/pt/${m[1]}/${m[2]}/jogos/${m[3]}`
  ],
  [
    new RegExp(`^/${SLUG}/${SLUG}/Player/${SLUG}$`),
    m => `/pt/${m[1]}/${m[2]}/jogadores/${m[3]}`
  ],
  [
    new RegExp(`^/${SLUG}/${SLUG}/PlayerStatsSummary$`),
    m => `/pt/${m[1]}/${m[2]}/estatisticas/resumo`
  ],
  [
    new RegExp(`^/${SLUG}/${SLUG}/PlayerStats$`),
    m => `/pt/${m[1]}/${m[2]}/estatisticas`
  ],
  [
    new RegExp(`^/${SLUG}/${SLUG}/Teams/${SLUG}$`),
    m => `/pt/${m[1]}/${m[2]}/times/${m[3]}`
  ],
  [
    new RegExp(`^/${SLUG}/${SLUG}/Phase/${SLUG}$`),
    m => `/pt/${m[1]}/${m[2]}/fases/${m[3]}`
  ],

  // The tournament root, which renders the tournament's default phase. Last on
  // purpose: it is the only rule with no literal segment, so every rule above
  // must get its chance first.
  [
    new RegExp(`^/${SLUG}/${SLUG}/?$`),
    m => (isReservedByCms(m[1]) ? null : `/pt/${m[1]}/${m[2]}`)
  ]
];

export const resolvePublicPath = (pathname: string): string | null => {
  for (const [pattern, toPath] of ROUTES) {
    const match = pathname.match(pattern);
    if (!match) continue;

    const publicPath = toPath(match);
    // A rule that matched the shape but declined (a reserved first segment)
    // ends the search: no later rule is more specific.
    return publicPath;
  }

  return null;
};
